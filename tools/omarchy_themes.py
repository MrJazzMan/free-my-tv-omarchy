"""miguel-custom: every official Omarchy theme for the TV, from a checkout of github.com/omacom/omarchy.
Writes web/themes.js (window.OMARCHY: the exact colors.toml palettes plus a focus-ring colour that reads at TV
distance) and, with --walls, the wallpapers: per theme its first 3 backgrounds in Omarchy's own order (sorted;
the first is the default) as 1920x1080 JPEGs, and a 384x216 thumbnail of the first (needs ffmpeg).
Usage: python3 tools/omarchy_themes.py OMARCHY_CHECKOUT [--walls]"""
import json
import os
import subprocess
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, 'web')
WALLS = os.path.join(WEB, 'wallpapers')
KEEP = {'tokyo-night', 'osaka-jade'}   # bundled earlier with all their backgrounds
NAMES = {'retro-82': 'Retro-82', 'rose-pine': 'Rosé Pine'}
IMAGE = ('.jpg', '.jpeg', '.png', '.webp')


def lum(hex_):
    c = [int(hex_[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def ring(p):
    """The accent when it stands out from the background (5:1; 4.5:1 on light themes, where the focused element
    also turns dark), else the theme's most legible bright colour."""
    if contrast(p['accent'], p['background']) >= (4.5 if p.get('mode') == 'light' else 5):
        return p['accent']
    names = ['cyan', 'bright_cyan', 'blue', 'bright_blue', 'yellow', 'bright_yellow', 'magenta', 'green']
    for n in names:
        if contrast(p[n], p['background']) >= 5:
            return p[n]
    best = max(names + ['accent'], key=lambda n: contrast(p[n], p['background']))
    return p[best] if contrast(p[best], p['background']) >= 4.5 else p['bright_foreground']


def ffmpeg(src, dst, w, h, q):
    subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', src, '-vf',
                    'scale=%d:%d:force_original_aspect_ratio=increase:flags=lanczos,crop=%d:%d,format=yuvj420p' % (w, h, w, h),
                    '-q:v', str(q), '-frames:v', '1', dst], check=True)


def main():
    themes_dir = os.path.join(sys.argv[1], 'themes')
    walls = '--walls' in sys.argv
    out = []
    for t in sorted(os.listdir(themes_dir)):
        d = os.path.join(themes_dir, t)
        if not os.path.isfile(os.path.join(d, 'colors.toml')):
            continue
        with open(os.path.join(d, 'colors.toml'), 'rb') as f:
            p = tomllib.load(f)
        bgs = sorted(n for n in os.listdir(os.path.join(d, 'backgrounds')) if n.lower().endswith(IMAGE))
        if walls:
            if t not in KEEP:
                for n in bgs[:3]:
                    ffmpeg(os.path.join(d, 'backgrounds', n), os.path.join(WALLS, t + '--' + os.path.splitext(n)[0] + '.jpg'), 1920, 1080, 4)
            os.makedirs(os.path.join(WALLS, 'thumbs'), exist_ok=True)
            ffmpeg(os.path.join(d, 'backgrounds', bgs[0]), os.path.join(WALLS, 'thumbs', t + '.jpg'), 384, 216, 5)
        c = {k: p[v] for k, v in (('bg', 'background'), ('dark', 'dark_background'), ('darker', 'darker_background'),
                                  ('lighter', 'lighter_background'), ('sel', 'selection'), ('muted', 'muted'),
                                  ('fg', 'foreground'), ('fgb', 'bright_foreground'), ('fgd', 'dark_foreground'),
                                  ('accent', 'accent'), ('red', 'red'), ('green', 'green'), ('yellow', 'yellow'),
                                  ('blue', 'blue'), ('magenta', 'magenta'), ('cyan', 'cyan'))}
        c['ring'] = ring(p)
        # miguel-custom: a theme's own Hyprland active border (a gradient, e.g. "rgba(26a269ee) rgba(2ec27eee) 45deg"),
        # as CSS for border-image; the other themes' active border is their accent (default/themed/hyprland.lua.tpl).
        if 'hyprland_active_border' in p:
            parts = p['hyprland_active_border'].split()
            stops = ['#' + x[5:11] for x in parts if x.startswith('rgba(')]
            angle = next((x for x in parts if x.endswith('deg')), '90deg')
            c['grad'] = 'linear-gradient(%s, %s)' % (angle, ', '.join(stops))
        out.append({'id': t, 'name': NAMES.get(t, t.replace('-', ' ').title()), 'mode': p.get('mode', 'dark'),
                    'wall': t + '--' + os.path.splitext(bgs[0])[0] + '.jpg', 'c': c})
    with open(os.path.join(WEB, 'themes.js'), 'w', encoding='utf-8') as f:
        f.write('/* miguel-custom: generated by tools/omarchy_themes.py from the colors.toml files of github.com/omacom/omarchy themes. */\n')
        f.write('window.OMARCHY = [\n' + ',\n'.join('  ' + json.dumps(x, ensure_ascii=False) for x in out) + '\n];\n')
    for x in out:
        print('%-17s %-5s ring %s%s' % (x['id'], x['mode'], x['c']['ring'], '' if x['c']['ring'] == x['c']['accent'] else ' (accent %s too weak)' % x['c']['accent']))


if __name__ == '__main__':
    main()
